/**
 * Get a random quote from an array
 */
export function getRandomQuote(quotes) {
  return quotes[Math.floor(Math.random() * quotes.length)];
}

/**
 * Локалізовані набори реплік.
 *
 * Українські масиви вище — джерело; для іншої мови `tList` віддає свій набір,
 * а якщо перекладу немає — той самий український. Довжини наборів можуть не
 * збігатися: вибір усе одно випадковий.
 */
export const QUOTE_SETS = {
  heroCorrect: () => tList('quotes_hero_correct', HERO_CORRECT_QUOTES),
  heroError: () => tList('quotes_hero_error', HERO_ERROR_QUOTES),
  boss: () => tList('quotes_boss', BOSS_QUOTES),
  enemy: () => tList('quotes_enemy', ENEMY_QUOTES),
  elite: () => tList('quotes_elite', ELITE_QUOTES),
  tips: () => tList('npc_tips', NPC_TIPS),
};

/** Випадкова репліка потрібного набору, уже потрібною мовою. */
export function randomQuote(setName) {
  return getRandomQuote(QUOTE_SETS[setName]?.() || ['']);
}
